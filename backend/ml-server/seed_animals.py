def main():
    batch = db.batch()
    for animal in ANIMALS:
        data = {k: v for k, v in animal.items() if k != "id"}
        data["adoptionStatus"] = "available"  # getAnimals() only returns these
        data["updatedAt"] = firestore.SERVER_TIMESTAMP
        batch.set(db.collection("animals").document(animal["id"]), data, merge=True)
    batch.commit()
    print(f"Added/updated {len(ANIMALS)} animals in Firestore:")
    for a in ANIMALS:
        print(f"  - {a['name']} ({a['breed']})  id: {a['id']}")


def check_photos():
    """Run `python seed_animals.py --check` to test every photo link before seeding."""
    import urllib.request

    for a in ANIMALS:
        url = a.get("photoUrl")
        if not url:
            print(f"  -  {a['name']}: no photo (app shows the species placeholder)")
            continue
        try:
            req = urllib.request.Request(url, method="HEAD", headers={"User-Agent": "PawPairSeed/1.0"})
            with urllib.request.urlopen(req, timeout=10) as res:
                ok = res.status == 200 and res.headers.get("Content-Type", "").startswith("image/")
            print(f"  {'OK' if ok else '??'} {a['name']}")
        except Exception as e:
            print(f"  XX {a['name']}: {e}")


if __name__ == "__main__":
    import sys

    if "--check" in sys.argv:
        check_photos()
    else:
        main()